const base = '/ai-training';

/**
 * Content links and image sources are written root-relative (`/guides/foo/`,
 * `/guides/foo.png`) so the markdown stays portable. This rehype plugin
 * prefixes those with the deploy base path at render time, for both
 * `<a href>` and `<img src>` (including raw HTML `<img>` tags).
 */
function rehypeBaseLinks() {
	/** @param {any} node */
	const visit = (node) => {
		const attr =
			node.type === 'element' && node.tagName === 'a'
				? 'href'
				: node.type === 'element' && node.tagName === 'img'
					? 'src'
					: null;
		if (attr) {
			const value = node.properties?.[attr];
			if (
				typeof value === 'string' &&
				value.startsWith('/') &&
				!value.startsWith('//') &&
				!value.startsWith(`${base}/`)
			) {
				node.properties[attr] = base + value;
			}
		}
		for (const child of node.children ?? []) visit(child);
	};
	return (/** @type {any} */ tree) => {
		visit(tree);
	};
}

/**
 * Sidebar entries for the topic map, read from the same YAML the map renders
 * (site/src/data/topics/<area>/<topic>.yaml), one collapsed group per area.
 * Topic pages are generated by src/pages/topics/[...id].astro, so these are
 * `link` items (Starlight prepends `base` to sidebar links).
 */
const AREA_ORDER = ['concepts', 'safety', 'using-agents', 'coding-with-agents', 'customizing-agents', 'building-agents'];
/** @type {Record<string, string>} */
const AREA_NAMES = {
	concepts: 'Concepts',
	safety: 'Safety',
	'using-agents': 'Using agents',
	'coding-with-agents': 'Coding with agents',
	'customizing-agents': 'Customizing agents',
	'building-agents': 'Building agents',
};
function topicSidebar() {
	const root = new URL('./src/data/topics/', import.meta.url);
	return AREA_ORDER.map((area) => {
		const dir = new URL(`${area}/`, root);
		const topics = readdirSync(dir)
			.filter((f) => f.endsWith('.yaml'))
			.map((f) => parseYaml(readFileSync(new URL(f, dir), 'utf8')))
			.sort((a, b) => a.name.localeCompare(b.name));
		return {
			label: AREA_NAMES[area],
			collapsed: true,
			items: topics.map((t) => ({ label: t.name, link: `/topics/${t.id}/` })),
		};
	});
}

