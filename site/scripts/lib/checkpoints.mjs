/**
 * The checkpoint export check's logic (spec S03 "Checkpoint export"): the
 * built `dist/data/checkpoints.json` must list every checkpoint of every
 * lesson page, and nothing else. `checkCheckpoints` reports a problem when
 *
 * - the file is missing or is not JSON, or its `version` is not 1;
 * - a checkpoint tag in a lesson page (`<Choice id=...>` and the other kinds
 *   in `KINDS`) has no item, or an item names a checkpoint no page has;
 * - an item lacks a required field or has one of the wrong type;
 * - an item's `concepts` is empty or names an id that no topic YAML defines.
 *
 * The export is generated by src/pages/data/checkpoints.json.ts from the same
 * source scan the pages use; this check reads the built file back so a
 * broken build step or a stale `dist/` shows up in CI. Like the other checks
 * it reads the MDX source directly rather than the content collections.
 * `scripts/check-checkpoints.mjs` is the command-line entry; tests import this.
 */
import { existsSync, readFileSync } from 'node:fs';
import { parse } from 'yaml';
import { lessonPages, yamlFiles } from './courses.mjs';
import { walkMdx } from './examples.mjs';

/** Component name to `kind`, the same table as src/lib/checkpoint-rules.ts. */
export const KINDS = {
	Choice: 'choice',
	MultiChoice: 'multi-choice',
	Match: 'match',
	Scenario: 'scenario',
	Predict: 'predict',
	Order: 'order',
	Sort: 'sort',
	Repair: 'repair',
};

/** Field name to the `typeof` it must have. `context`, `options` and `answer` may be null and are not listed. */
export const REQUIRED = {
	id: 'string',
	lesson: 'string',
	kind: 'string',
	objective: 'string',
	stem: 'string',
	hint: 'string',
	reviewable: 'boolean',
	revision: 'number',
};

/** Every concept id under `topicsDir` (site/src/data/topics). */
export function conceptIds(topicsDir) {
	return new Set(yamlFiles(topicsDir).flatMap((p) => (parse(readFileSync(p, 'utf8')).concepts ?? []).map((c) => c.id)));
}

/**
 * `<lesson>#<id>` for every checkpoint tag in every lesson page under
 * `contentDir`. The id is read from the first `id="..."` after the tag name,
 * which is how every checkpoint in the repo is written; the build itself
 * rejects a tag without one.
 */
export function pageCheckpointIds(contentDir) {
	const lessons = lessonPages(contentDir);
	const out = new Set();
	const TAG = new RegExp(`<(${Object.keys(KINDS).join('|')})\\b[^>]*?\\bid="([^"]+)"`, 'g');
	for (const p of walkMdx(contentDir)) {
		const lesson = p.slice(contentDir.length + 1).replace(/\.mdx$/, '');
		if (!lessons.has(lesson)) continue;
		for (const m of readFileSync(p, 'utf8').matchAll(TAG)) out.add(`${lesson}#${m[2]}`);
	}
	return out;
}

/**
 * Check the export at `file` against the pages under `contentDir` and the
 * topics under `topicsDir`. Returns `{ errors: string[], items: number }`.
 */
export function checkCheckpoints(file, contentDir, topicsDir) {
	const errors = [];
	const fail = (msg) => errors.push(msg);
	if (!existsSync(file)) return { errors: [`${file} does not exist; run site-build first`], items: 0 };
	let data;
	try {
		data = JSON.parse(readFileSync(file, 'utf8'));
	} catch (e) {
		return { errors: [`${file}: not JSON: ${e.message}`], items: 0 };
	}
	if (data?.version !== 1) fail(`version is ${JSON.stringify(data?.version)}, expected 1`);
	if (!Array.isArray(data?.items)) return { errors: [...errors, 'no items list'], items: 0 };

	const known = conceptIds(topicsDir);
	const kinds = new Set(Object.values(KINDS));
	const expected = pageCheckpointIds(contentDir);
	const seen = new Set();
	for (const [i, item] of data.items.entries()) {
		const where =
			typeof item?.lesson === 'string' && typeof item?.id === 'string' ? `${item.lesson}#${item.id}` : `items[${i}]`;
		for (const [field, type] of Object.entries(REQUIRED)) {
			const actual = typeof item?.[field];
			if (actual !== type) fail(`${where}: ${field} must be a ${type}`);
		}
		for (const field of ['context', 'options', 'answer']) {
			if (!(field in (item ?? {}))) fail(`${where}: ${field} is missing (null when absent)`);
		}
		if (!kinds.has(item?.kind)) fail(`${where}: kind ${JSON.stringify(item?.kind)} is not a checkpoint kind`);
		if (!Array.isArray(item?.concepts) || item.concepts.length === 0)
			fail(`${where}: concepts must list at least one id`);
		else
			for (const c of item.concepts)
				if (!known.has(c)) fail(`${where}: concept ${JSON.stringify(c)} is not in the topic YAML`);
		if (seen.has(where)) fail(`${where}: listed twice`);
		seen.add(where);
		if (where.includes('#') && !expected.has(where)) fail(`${where}: no lesson page has this checkpoint`);
	}
	for (const id of [...expected].sort()) {
		if (!seen.has(id)) fail(`${id}: checkpoint in the lesson page is missing from the export`);
	}
	return { errors, items: data.items.length };
}
